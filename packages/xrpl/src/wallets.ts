import fs from "node:fs";
import path from "node:path";
import { Wallet } from "xrpl";
import type { ECDSA } from "xrpl";
import { networkName, type AccountName, type AccountsFile, type NetworkName } from "@moonshift/shared";
import dotenv from "dotenv";

export const ALL_ACCOUNT_NAMES: readonly AccountName[] = [
  "TDX_ISSUER",
  "SHARE_ISSUER",
  "CONTRACT_ISSUER",
  "TREASURY_GPU_A",
  "TREASURY_GPU_B",
  "PROTOCOL_FEES",
  "LENDING_POOL",
  "ORACLE",
  "ALICE",
  "BOB",
  "CAROL",
  "DEV",
] as const;

function findRepoRoot(dir = process.cwd()): string {
  let curr = path.resolve(dir);
  while (curr !== path.dirname(curr)) {
    if (fs.existsSync(path.join(curr, "package.json"))) {
      try {
        const pkg = JSON.parse(fs.readFileSync(path.join(curr, "package.json"), "utf8"));
        if (pkg.workspaces) return curr;
      } catch {
        // continue
      }
    }
    curr = path.dirname(curr);
  }
  return process.cwd();
}

export const REPO_ROOT = findRepoRoot();
export const ENV_FILE_PATH = path.join(REPO_ROOT, ".env");
// Public addresses per network: contracts/accounts.<network>.json.
export function accountsJsonPath(net: NetworkName = networkName()): string {
  return path.join(REPO_ROOT, "contracts", `accounts.${net}.json`);
}
/** @deprecated testnet path only; use accountsJsonPath(). */
export const ACCOUNTS_JSON_PATH = accountsJsonPath("testnet");

// Load .env if present
if (fs.existsSync(ENV_FILE_PATH)) {
  dotenv.config({ path: ENV_FILE_PATH, override: false });
}

export function getSigningAlgorithm(seed: string): ECDSA {
  // String values, not the ECDSA enum: xrpl is CommonJS and its ECDSA export is not
  // visible to Node ESM named imports, which crashed the api at startup.
  return (seed.startsWith("sEd") ? "ed25519" : "ecdsa-secp256k1") as ECDSA;
}

export function loadWalletFromSeed(seed: string): Wallet {
  const algorithm = getSigningAlgorithm(seed);
  return Wallet.fromSeed(seed.trim(), { algorithm });
}

// Testnet seeds keep their original names (ALICE_SEED). Devnet seeds are
// separate accounts with a DEVNET_ prefix (DEVNET_ALICE_SEED).
export function getSeedEnvKey(name: AccountName, net: NetworkName = networkName()): string {
  return net === "testnet" ? `${name}_SEED` : `${net.toUpperCase()}_${name}_SEED`;
}

// User accounts (U_<address>): custodial devnet accounts the api holds for each
// connected wallet. Registered at runtime from the api's encrypted store, never
// read from or written to .env.
const userWallets = new Map<string, Wallet>();

export function isUserAccount(name: string): boolean {
  return name.startsWith("U_");
}

export function userAccountName(address: string): AccountName {
  return `U_${address}`;
}

export function registerUserAccount(seed: string): { name: AccountName; address: string } {
  const wallet = loadWalletFromSeed(seed);
  const name = userAccountName(wallet.address);
  userWallets.set(name, wallet);
  return { name, address: wallet.address };
}

export function registeredUserAccounts(): AccountName[] {
  return [...userWallets.keys()] as AccountName[];
}

export function getAccountWallet(name: AccountName): Wallet {
  const user = userWallets.get(name);
  if (user) return user;
  if (isUserAccount(name)) throw new Error(`Unknown user account ${name}`);
  const envKey = getSeedEnvKey(name);
  const seed = process.env[envKey];
  if (!seed) {
    throw new Error(`Missing ${envKey} in environment. Run setupNetwork() or populate .env first.`);
  }
  return loadWalletFromSeed(seed);
}

export function loadAccountsJson(): AccountsFile {
  const file = accountsJsonPath();
  if (fs.existsSync(file)) {
    try {
      const raw = fs.readFileSync(file, "utf8");
      return JSON.parse(raw);
    } catch {
      // return default
    }
  }
  const empty: AccountsFile = {};
  for (const n of ALL_ACCOUNT_NAMES) {
    empty[n] = { address: "" };
  }
  return empty;
}

export function saveAccountsJson(data: AccountsFile): void {
  const file = accountsJsonPath();
  const dir = path.dirname(file);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  const payload = {
    _note: `Public ${networkName()} addresses generated by packages/xrpl setupNetwork(). Safe to commit. Never put seeds here.`,
    ...data,
  };
  fs.writeFileSync(file, JSON.stringify(payload, null, 2) + "\n", "utf8");
}

export function appendOrUpdateEnvSeeds(seeds: Partial<Record<AccountName, string>>): void {
  let content = "";
  if (fs.existsSync(ENV_FILE_PATH)) {
    content = fs.readFileSync(ENV_FILE_PATH, "utf8");
  } else if (fs.existsSync(path.join(REPO_ROOT, ".env.example"))) {
    content = fs.readFileSync(path.join(REPO_ROOT, ".env.example"), "utf8");
  }

  const lines = content.split("\n");
  const updatedKeys = new Set<string>();

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const match = line.match(/^([A-Z0-9_]+)=/);
    if (match) {
      const key = match[1];
      for (const [account, seed] of Object.entries(seeds)) {
        if (key === getSeedEnvKey(account as AccountName) && seed) {
          lines[i] = `${key}=${seed}`;
          updatedKeys.add(key);
        }
      }
    }
  }

  for (const [account, seed] of Object.entries(seeds)) {
    const key = getSeedEnvKey(account as AccountName);
    if (!updatedKeys.has(key) && seed) {
      lines.push(`${key}=${seed}`);
    }
  }

  fs.writeFileSync(ENV_FILE_PATH, lines.join("\n"), "utf8");

  // Also update process.env for the running process
  for (const [account, seed] of Object.entries(seeds)) {
    if (seed) {
      process.env[getSeedEnvKey(account as AccountName)] = seed;
    }
  }
}

export function getAccountAddress(name: AccountName | string): string {
  if (typeof name === "string" && name.startsWith("r") && name.length >= 25 && name.length <= 35) {
    return name;
  }
  if (isUserAccount(name as AccountName)) return name.slice(2);
  const envKey = getSeedEnvKey(name as AccountName);
  const seed = process.env[envKey];
  if (seed) {
    return loadWalletFromSeed(seed).address;
  }
  const file = loadAccountsJson();
  if (file[name as AccountName]?.address) {
    return file[name as AccountName].address;
  }
  throw new Error(`Account address unknown for ${name}. Must fund or set ${envKey}.`);
}
